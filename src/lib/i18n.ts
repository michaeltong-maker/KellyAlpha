export type MessageKey = keyof typeof messages.en;

function resolveLang(l: string): Lang {
  return l === 'zh' || l === 'zh-Hans' ? l : 'en';
}

export function useT() {
  const { persisted } = useApp();
  const lang = resolveLang(persisted.language);
  return (key: MessageKey, params?: Record<string, string | number>): string => {
    const template = (messages[lang] as Record<string, string>)[key]
      ?? (messages.en as Record<string, string>)[key]
      ?? key;
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''));
  };
}

export function useLang(): Lang {
  const { persisted } = useApp();
  return resolveLang(persisted.language);
}
